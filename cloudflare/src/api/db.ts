export const migrations: string[][] = [schema, migration2, migration3, migration4, migration5, migration6];

let schemaReady = false;

/**
 * Brings the schema up to date once per isolate. The Go server does this at
 * startup; here the first request in each isolate checks the version and only
 * migrates when the database is behind.
 */
export async function ensureSchema(db: DB): Promise<void> {
  if (schemaReady) return;
  let version = -1;
  try {
    const r = await db.row(`SELECT COALESCE(MAX(version),0) AS v FROM schema_migrations`);
    version = Number(r?.v ?? 0);
  } catch {
    version = -1; // table missing: run the full migration below
  }
  if (version > migrations.length) throw new Error("database schema is newer than this server");
  if (version === migrations.length) {
    schemaReady = true;
    return;
  }
  await db.tx(async (q) => {
    await q.query(`SELECT pg_advisory_xact_lock(917442621)`);
    await q.query(`CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)`);
    const r = (await q.query(`SELECT COALESCE(MAX(version),0) AS v FROM schema_migrations`)).rows[0];
    const current = Number(r?.v ?? 0);
    if (current > migrations.length) throw new Error("database schema is newer than this server");
    for (let i = current; i < migrations.length; i++) {
      for (const stmt of migrations[i]) await q.query(stmt);
      await q.query(`INSERT INTO schema_migrations(version,applied_at) VALUES($1,$2)`, [i + 1, now()]);
    }
  });
  schemaReady = true;
}
