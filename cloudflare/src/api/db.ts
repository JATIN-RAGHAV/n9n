// PostgreSQL access through Hyperdrive with node-postgres. One client per
// request; Hyperdrive pools the real connections.
import { Client } from "pg";
import { now } from "./util";

export type Row = Record<string, any>;

export interface Queryer {
  query(text: string, params?: unknown[]): Promise<{ rows: Row[]; rowCount: number | null }>;
}

export class DB {
  constructor(private client: Client) {}

  async rows(text: string, params: unknown[] = [], q: Queryer = this.client): Promise<Row[]> {
    return (await q.query(text, params)).rows;
  }
  async row(text: string, params: unknown[] = [], q: Queryer = this.client): Promise<Row | undefined> {
    return (await q.query(text, params)).rows[0];
  }
  async exec(text: string, params: unknown[] = [], q: Queryer = this.client): Promise<number> {
    return (await q.query(text, params)).rowCount ?? 0;
  }
  get q(): Queryer {
    return this.client;
  }

  /** Runs fn in a transaction; commits on success and rolls back on any throw. */
  async tx<T>(fn: (q: Queryer) => Promise<T>): Promise<T> {
    await this.client.query("BEGIN");
    try {
      const out = await fn(this.client);
      await this.client.query("COMMIT");
      return out;
    } catch (e) {
      await this.client.query("ROLLBACK").catch(() => {});
      throw e;
    }
  }
}

export async function connect(connectionString: string): Promise<{ db: DB; close: () => Promise<void> }> {
  const client = new Client({ connectionString });
  await client.connect();
  return { db: new DB(client), close: () => client.end().catch(() => {}) };
}

